MUTATIONS = [(entry, "lineage") for entry in LINEAGE] + [(entry, "bookstall") for entry in BOOKSTALL]


def _env(**extra):
    return dict(os.environ, PYTHONDONTWRITEBYTECODE="1", **extra)


def run(lineage_path: pathlib.Path, bookstall_path: pathlib.Path) -> str:
    out = subprocess.run(PYTEST, env=_env(LINEAGE_SOURCE=str(lineage_path), BOOKSTALL_SOURCE=str(bookstall_path)),
                         capture_output=True, text=True, cwd=ROOT)
    if out.returncode == 0:
        return ""
    text = out.stdout + out.stderr
    if "error during collection" in text or "IndentationError" in text or "SyntaxError" in text:
        raise RuntimeError("the mutant does not even import; that is a broken anchor, not a killed defence:\n"
                           + text[-600:])
    m = re.search(r"^FAILED tests/test_pure\.py::(.+?)(?: - .*)?$", text, re.M)
    if not m:
        raise RuntimeError("a test failed but its name could not be read:\n" + text[-800:])
    return m.group(1)


def main() -> int:
    baseline = subprocess.run(PYTEST, env=_env(), capture_output=True, text=True, cwd=ROOT)
    if baseline.returncode != 0:
        print("the unmutated suite does not pass; a mutation table over a failing suite proves nothing")
        print((baseline.stdout + baseline.stderr)[-600:])
        return 3
    rows, escaped = [], []
    with tempfile.TemporaryDirectory() as tmp:
        for k, (entry, target) in enumerate(MUTATIONS):
            name = entry[0]
            pairs = entry[1] if len(entry) == 2 else [(entry[1], entry[2])]
            mutant = SOURCES[target]
            for old, new in pairs:
                if mutant.count(old) != 1:
                    print(f"  ! anchor found {mutant.count(old)} times in {FILES[target]}, expected once: {name}")
                    return 2
                mutant = mutant.replace(old, new)
            paths = {}
            for which in SOURCES:
                paths[which] = pathlib.Path(tmp) / f"{which}_{k}.py"
                paths[which].write_text(mutant if which == target else SOURCES[which], encoding="utf-8")
            killer = run(paths["lineage"], paths["bookstall"])
            (rows if killer else escaped).append((name, target, killer))
            print(f"  {'killed ' if killer else 'ESCAPED'}  {FILES[target]}: {name}" + (f"  <- {killer}" if killer else ""))
    if escaped:
        print(f"\n{len(escaped)} mutant(s) escaped; no table written.")
        return 1
